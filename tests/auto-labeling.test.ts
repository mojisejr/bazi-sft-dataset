import { describe, expect, test } from "vitest";

import {
  buildDraftPayloadFromAutoLabelingRecord,
  createDeterministicRawInputs,
  pruneImportedQueueCases,
  type AutoLabelingQueueDocument,
} from "@/lib/bazi/auto-labeling";
import {
  CalculatedStateSchema,
  REQUIRED_ANNOTATION_DIMENSION_NAMES,
} from "@/lib/bazi/schema-types";

function createQueueRecord() {
  return {
    queueId: "25d0e97b-6fb2-4b2b-8d5d-86fa43d7b8c2",
    intentDomain: "love" as const,
    rawInput: {
      birthDate: "1992-08-21",
      birthTime: "14:35",
      gender: "female",
      province: "Bangkok",
      calendarSystem: "solar" as const,
      timezone: "Asia/Bangkok",
    },
    calculatedState: CalculatedStateSchema.parse({
      fourPillars: {
        year: { stem: "壬", branch: "申", hiddenStems: ["庚", "壬", "戊"] },
        month: { stem: "戊", branch: "申", hiddenStems: ["庚", "壬", "戊"] },
        day: { stem: "己", branch: "巳", hiddenStems: ["丙", "庚", "戊"] },
        hour: { stem: "辛", branch: "未", hiddenStems: ["己", "丁", "乙"] },
      },
      dayMaster: "己",
      strengthScore: 3.07,
      tenGods: {
        yearStem: "正财",
        yearBranch: "伤官,正财,劫财",
        monthStem: "劫财",
        monthBranch: "伤官,正财,劫财",
        dayStem: "比肩",
        dayBranch: "正印,伤官,劫财",
        hourStem: "食神",
        hourBranch: "比肩,偏印,七杀",
      },
      twelveQi: {
        yearBranch: "沐浴",
        monthBranch: "沐浴",
        dayBranch: "帝旺",
        hourBranch: "冠带",
      },
      elementMetaphors: [
        {
          element: "earth",
          metaphor: "fertile cultivated soil that nurtures, absorbs, and organizes",
        },
      ],
      sixtyJiaziCorePersona: {
        code: "己巳",
        narrative: "Builds influence patiently, then turns preparation into visible results when timing opens.",
        precedenceNotes: ["Near solar-term boundary."],
      },
    }),
    annotationData: {
      version: "1.6" as const,
      reviewSummary: "Love-domain draft generated by the Copilot sinsae pipeline.",
      dimensions: REQUIRED_ANNOTATION_DIMENSION_NAMES.map((dimensionName) => ({
        dimension_name: dimensionName,
        thought_process: `Reasoning for ${dimensionName}`,
        final_prediction: `Prediction for ${dimensionName}`,
        supporting_signals: [],
      })),
    },
  };
}

describe("auto-labeling helpers", () => {
  test("creates deterministic raw inputs from a fixed seed", () => {
    const firstBatch = createDeterministicRawInputs({ count: 3, seed: 20260416 });
    const secondBatch = createDeterministicRawInputs({ count: 3, seed: 20260416 });

    expect(firstBatch).toEqual(secondBatch);
    expect(firstBatch).toHaveLength(3);
    expect(firstBatch[0]?.timezone).toBe("Asia/Bangkok");
  });

  test("builds a draft payload from an auto-labeling record", () => {
    const payload = buildDraftPayloadFromAutoLabelingRecord(createQueueRecord());

    expect(payload.status).toBe("draft");
    expect(payload.intentDomain).toBe("love");
    expect(payload.annotationData.dimensions).toHaveLength(15);
    expect(payload.metadata).toEqual({
      generation: {
        source: "agent-import",
        queueBatchId: "25d0e97b-6fb2-4b2b-8d5d-86fa43d7b8c2",
      },
    });
  });

  test("prunes imported queue ids from the queue document", () => {
    const queueDocument: AutoLabelingQueueDocument = {
      version: "1",
      generatedAt: "2026-04-16T16:00:00.000Z",
      seed: 20260416,
      cases: [
        {
          queueId: "25d0e97b-6fb2-4b2b-8d5d-86fa43d7b8c2",
          intentDomain: "love",
          rawInput: createQueueRecord().rawInput,
          calculatedState: createQueueRecord().calculatedState,
        },
        {
          queueId: "be950d1b-6517-4dcc-bdc8-db102d39ff30",
          intentDomain: "love",
          rawInput: {
            ...createQueueRecord().rawInput,
            birthDate: "1988-05-14",
          },
          calculatedState: createQueueRecord().calculatedState,
        },
      ],
    };

    const pruned = pruneImportedQueueCases(queueDocument, [
      "25d0e97b-6fb2-4b2b-8d5d-86fa43d7b8c2",
    ]);

    expect(pruned.cases).toHaveLength(1);
    expect(pruned.cases[0]?.queueId).toBe("be950d1b-6517-4dcc-bdc8-db102d39ff30");
  });
});
