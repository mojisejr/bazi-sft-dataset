/** รวมย่อหน้า (ตัดค่าว่าง) ด้วยบรรทัดว่างคั่น */
export function composeParagraphs(parts: Array<string | null | undefined>): string {
  return parts
    .map((part) => part?.trim())
    .filter((part): part is string => Boolean(part))
    .join("\n\n");
}
