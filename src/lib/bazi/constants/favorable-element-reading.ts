/**
 * ประกอบเนื้อกล่อง "ธาตุเสริมดวง / ธาตุที่ควรเลี่ยง" จากธาตุที่ engine คำนวณ
 * favorable = ธาตุที่ดวงต้องการ (用神) · avoid = ธาตุที่ควรเลี่ยง (忌神, มักนำด้วยธาตุพิฆาตดิถี 官杀)
 */
export function buildFavorableSummaryText(
  favorable: ElementTh[],
  avoid: ElementTh[],
): string {
  const favLine = favorable.length
    ? favorable.map((e) => `- **ธาตุ${e}**: ${FAVORABLE_ELEMENT_MEANING[e]}`).join("\n")
    : "- (ดวงพิเศษ — พิจารณาเป็นรายกรณี)";
  const avoidLine = avoid.length
    ? avoid.map((e) => `- **ธาตุ${e}**: ${AVOID_ELEMENT_MEANING[e]}`).join("\n")
    : "";
  const favHead = `ธาตุเสริมดวง (用神) = ${favorable.join(", ") || "-"}`;
  const avoidHead = avoid.length ? `\n\nธาตุที่ควรเลี่ยง/ระวัง (忌神) = ${avoid.join(", ")}` : "";
  return [favHead, favLine, avoidHead && avoidHead.trim(), avoidLine]
    .filter((x) => x && String(x).trim())
    .join("\n");
}
