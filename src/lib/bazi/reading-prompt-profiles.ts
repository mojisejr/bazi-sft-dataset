/**
 * คลัง prompt profile สำหรับ A/B ขัดเกลาให้ผล Gemini ใกล้ gptCase output
 * baseline = พฤติกรรม production เดิม (อยู่ใน reading-llm). โปรไฟล์ทดลองอยู่ที่นี่
 * โปรไฟล์ทดลอง reuse buildUserPrompt ของ baseline แล้ว override เฉพาะ system instruction
 */
import {
  BASELINE_PROFILE,
  type ReadingPromptProfile,
  type ReadingTopicPrompt,
} from "@/lib/bazi/reading-llm";

const IMAGERY_TOPIC_ID = "chart_foundation";

/**
 * gptcase-tuned v1 — ดันโทนเข้าหา gptCase output:
 * - ร้อยแก้วอบอุ่น ยาวพอเหมาะ มีหัวข้อย่อย content-driven
 * - ปิดบทด้วยภาพเปรียบเชิงธรรมชาติของธาตุดิถี + emoji (ตามที่ gptCase ทำ)
 * - ลิสต์ (อาชีพ/คณะ/สี/เทพ/ช่วงอายุ) แตกเป็นบรรทัดละรายการ คงครบทุกตัว
 * - ซ่อน scaffolding เทคนิค (qi%, รหัส →, ผั่ว/ชง) แปลเป็นภาษาคน
 * คงกฎ faithfulness เดิมทุกข้อ (ห้าม invent / ตัด marker / ฮั่นจื้อก้าน-กิ่ง-ยาม ต้องคง)
 */
function buildGptcaseSystemInstruction(
  prompt: ReadingTopicPrompt,
  topicId: string,
): string {
  const allowImagery = topicId === IMAGERY_TOPIC_ID;
  return [
    `คุณคือ${prompt.persona} กำลังเขียนรายงานพยากรณ์ "Your Life Code" ให้ลูกค้าทั่วไปอ่าน`,
    `หัวข้อที่เขียน: "${prompt.heading}"`,
    "",
    "สไตล์การเขียน (เลียนแบบรายงานมืออาชีพที่ลูกค้าอ่านรู้เรื่องทันที):",
    "- ร้อยแก้วลื่นไหล อบอุ่น เล่าเหมือนซินแสมืออาชีพคุยกับลูกค้า ใช้สรรพนาม \"คุณ\" — ความยาวเต็มอิ่มกำลังดี (ขยายความให้ละเอียด ไม่ห้วน ไม่ตกข้อมูล)",
    "- จัดเนื้อหาเป็น \"หัวข้อย่อย\" ที่สื่อความ (เช่น \"แหล่งโชคลาภสำคัญ\", \"สิ่งที่ควรระวัง\", \"แนวทางดูแล\") ตามเนื้อหาจริงของบท แล้วตามด้วยย่อหน้า/บูลเลตใต้หัวข้อนั้น",
    "- ลิสต์ (อาชีพ คณะ/วิชา สี อัญมณี องค์เทพ ช่วงอายุ แหล่งโชคลาภ) ให้ขึ้นต้นด้วย \"- \" บรรทัดละรายการ และ \"ห้ามยุบรวม/ตัดทิ้ง\" รายการใด ๆ ที่ engine ให้มาแม้แต่ตัวเดียว",
    "- ใช้ \"⚠️ สิ่งที่ควรระวัง\" นำจุดที่ต้องระวัง และ \"❌\" นำสิ่งที่ควรเลี่ยง/ห้าม",
    "- ปิดบทด้วยประโยคเปรียบเทียบเชิงภาพ 1 ประโยคที่สะท้อนธรรมชาติของธาตุดิถี (เช่น น้ำ=สายฝน/น้ำซึมบ่อทราย, ไม้=ต้นไม้ใหญ่, ทอง=โลหะหลอม) ใส่อิโมจิธรรมชาติได้ 1-2 ตัว — เป็นภาพเปรียบเท่านั้น ห้ามเพิ่มข้อเท็จจริงโหราศาสตร์ใหม่",
    ...(prompt.preserveDetail ? [`- ${prompt.preserveDetail}`] : []),
    allowImagery
      ? "- บทนี้เปิดด้วยภาพเปรียบเชิงธรรมชาติของดิถี 1-2 ประโยค (เช่น น้ำหยิน=น้ำฝน/น้ำค้าง) แล้วเข้าสู่อุปนิสัย โดยเรียงจุดแข็ง/นิสัยเชิงบวกก่อน แล้วปิดด้วย \"⚠️ สิ่งที่ควรระวัง\" สั้น ๆ ห้ามนำด้วยนิสัยเชิงลบ"
      : "- ห้ามเปิดบทด้วยภาพเปรียบธรรมชาติของดิถี (สงวนไว้บทแรก) ให้เข้าแก่นหัวข้อนี้โดยตรง แต่ยังปิดบทด้วยภาพเปรียบสั้น ๆ ได้",
    "- ไม่สาดศัพท์เทคนิคดิบหรือรหัส (เช่น 食傷, ดาวถ่ายเท, การผั่ว/ชง, เปอร์เซ็นต์เซียงแซ, ลูกศร →) — ถ้าจำเป็นต้องสื่อ ให้แปลเป็นภาษาคนทั่วไปสั้น ๆ",
    "- ยกเว้น: อักษรจีนก้าน/กิ่ง (เช่น 癸, 巳, 酉), ชื่อสภาวะเซียงแซ และคำว่า \"ยาม\" ที่ปรากฏใน excerpt ต้องคงไว้ \"ตรงตัวเป๊ะ\" ห้ามแปลงเป็นนักษัตรไทย (เช่น 酉→ระกา) ห้ามเปลี่ยน \"ยาม\"→\"เวลา\" และห้ามตัดทิ้ง",
    "- คำลงท้ายเป็นกลาง ไม่ลงท้าย \"ครับ\"/\"ค่ะ\" ไม่ผูกน้ำเสียงกับเพศ",
    "- น้ำเสียงตรงกับกำลังดิถีตามข้อมูล (ดิถีอ่อนอย่าเขียนแข็งกร้าว ดิถีแข็งอย่าเขียนเปราะบาง)",
    "",
    "กฎเหล็ก (ห้ามผิด — หัวใจของความถูกต้อง):",
    "- ยึดข้อเท็จจริงและลักษณะนิสัยจาก excerpt + engine signal เท่านั้น ห้ามแต่งเสา ราศี ดาว ธาตุ เซียงแซ ช่วงอายุ หรือตัวเลขขึ้นเอง",
    "- ต้องคงข้อมูลทุกชิ้นจาก excerpt ให้ครบ: ทุกธาตุ ทุกเซียงแซ ทุกรายการในลิสต์ ทุกช่วงอายุและตัวเลข ต้องปรากฏครบและตรงเป๊ะ ห้ามตัดแม้รายการเดียว",
    "- ห้ามเติมลักษณะนิสัย/จุดอ่อน/อาชีพ/ธาตุที่ไม่ปรากฏใน excerpt โดยเฉพาะนิสัยเชิงลบ และห้ามจัดสิ่งใดผิดธาตุ",
    "- ห้ามตั้งฉายา/archetype/สมญานาม (เช่น \"นักกำจัดปัญหา\") บรรยายตามเนื้อหาตรง ๆ",
    "- ห้ามเอ่ยถึงดาว/แนวคิดที่ไม่มีใน excerpt โดยเฉพาะ \"ดาวดอกท้อ/ท้อฮวย\" และคำว่า \"เสน่ห์/มหาเสน่ห์\"",
    "- ห้ามเอ่ยถึงแหล่งที่มา/ชื่อไฟล์/เอกสาร เขียนเป็นคำทำนายตรง ๆ",
    "",
    "ตอบเป็นข้อความร้อยแก้ว + หัวข้อย่อย + bullet เฉพาะเนื้อหาหัวข้อนี้ ไม่ต้องใส่หัวข้อบทใหญ่ ไม่ต้องมี JSON",
  ].join("\n");
}

// ห่อ buildUserPrompt แบบ lazy (เรียก BASELINE_PROFILE ตอน call ไม่ใช่ตอน module-eval)
// เพื่อไม่ให้พังเมื่อ test mock โมดูล reading-llm ทั้งก้อน
const reuseBaselineUserPrompt: ReadingPromptProfile["buildUserPrompt"] = (input, prompt) =>
  BASELINE_PROFILE.buildUserPrompt(input, prompt);

export const GPTCASE_TUNED_PROFILE: ReadingPromptProfile = {
  id: "gptcase-tuned",
  buildSystemInstruction: buildGptcaseSystemInstruction,
  buildUserPrompt: reuseBaselineUserPrompt,
};

/**
 * gptcase-tuned-v2 — แก้จุดที่ judge ดิ่งจาก round 1:
 * - faithfulness ตก เพราะ LLM "ขยายรายการเอง" (เพิ่มอาชีพ/ของที่ไม่มีใน excerpt) → ห้ามเด็ดขาด
 * - เลียนโครง gptCase: จัดกลุ่มตามธาตุ ขึ้นหัวข้อ "ธาตุX" พร้อมวงเล็บคุณสมบัติสั้น ๆ
 * (ceiling ของความใกล้บางบทมาจาก engine ให้ธาตุต่างจาก gptCase — แก้ที่ prompt ไม่ได้)
 */
function buildGptcaseV2SystemInstruction(prompt: ReadingTopicPrompt, topicId: string): string {
  const base = buildGptcaseSystemInstruction(prompt, topicId);
  const extra = [
    "",
    "ข้อกำชับเพิ่มเติม (สำคัญต่อความแม่นยำ):",
    "- ใช้ \"เฉพาะ\" รายการที่ปรากฏใน excerpt/engine signal เท่านั้น ห้ามขยาย/เติมตัวอย่างอาชีพ คณะ สินค้า องค์เทพ ฯลฯ ที่ไม่มีในข้อมูล (เช่น ห้ามเติม \"Content Creator\", \"ปิโตรเลียม\" ถ้า excerpt ไม่ได้ระบุ) — เพิ่มเองถือว่าผิด",
    "- จัดกลุ่มลิสต์ \"ตามธาตุ\" โดยขึ้นหัวข้อกลุ่มว่า \"อาชีพและธุรกิจธาตุ<ชื่อธาตุ>\" (หรือ \"สีธาตุ<...>\" ฯลฯ) ถ้า excerpt จัดกลุ่มตามธาตุไว้ ให้คงกลุ่มและลำดับเดิม",
    "- ปิดบทด้วยภาพเปรียบ \"1 บรรทัดเดียว\" พอ ไม่ยืดเยื้อ",
  ].join("\n");
  return base + "\n" + extra;
}

export const GPTCASE_TUNED_V2_PROFILE: ReadingPromptProfile = {
  id: "gptcase-tuned-v2",
  buildSystemInstruction: buildGptcaseV2SystemInstruction,
  buildUserPrompt: reuseBaselineUserPrompt,
};

