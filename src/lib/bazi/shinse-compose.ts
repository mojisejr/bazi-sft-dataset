export const GEN_MARK = `⟨ยังไม่มีข้อมูลจากตำราสำหรับกล่องนี้ — ให้ "ร่าง" คำอ่านจากสี่เสา/ดิถี/กำลังที่ให้ (หลักโหราศาสตร์จีน) เป็นจุดตั้งต้นให้ซินแสแก้ แต่ต้อง: (1) ขึ้นต้นกล่องด้วยป้าย "${AI_DRAFT_TAG}" (2) เลือก "ทิศทางเดียว" ที่หลักโหราหนุนที่สุดแล้วเขียนฟันธงชัดเจนเหมือนกล่องอื่น — ห้ามแทงกั๊กสองขั้วหรือถมคำเผื่อ (น่าจะ/อาจจะ/มีแนวโน้ม) จนอ่านไม่รู้เรื่อง (3) อิงเฉพาะเสา/ธาตุที่มีจริง ห้ามแต่งเชี่ยงแซ/เสาที่ไม่มี⟩`;

/** กล่อง → box-markdown [[box=หัวข้อ]] เนื้อ [[/box]] (รูปแบบเดียวกับ few-shot + ที่ client parse)
 *  กล่อง body ว่าง → ใส่ GEN_MARK ให้ AI รู้ว่าต้อง "เขียนเอง" (ไม่ใช่ "ขัดเกลา") */
export function boxesToMarkdown(boxes: ReadingBox[]): string {
  return (boxes || [])
    .map((b) => {
      const body = (b.body ?? "").trim();
      // body ว่าง หรือ กล่อง template generic (ยังไม่ curate) → ให้ AI เขียนเอง
      const needGenerate = !body || b.templatePrefill;
      return `[[box=${b.title ?? ""}]]\n${needGenerate ? GEN_MARK : body}\n[[/box]]`;
    })
    .join("\n");
}

/** เลือกตัวอย่าง ≤2 อัน — เอาธาตุตรงดวงนี้ก่อน แล้วเติมธาตุอื่น (กระจายสำนวน) */
export function pickFewshot(topicId: string, dayElement: string): FewshotExample[] {
  const pool = BANK[topicId] ?? [];
  if (pool.length === 0) return [];
  const same = pool.find((e) => e.dayElement === dayElement);
  const others = pool.filter((e) => e !== same);
  return [same, others[0]].filter(Boolean) as FewshotExample[];
}

