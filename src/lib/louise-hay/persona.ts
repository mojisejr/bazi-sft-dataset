export function detectEmotionalDistress(text: string): boolean {
  return /หมดไฟ|ดิ่ง(มาก|สุด|ๆ)?|ซึมเศร้า|สิ้นหวัง|หดหู่|โดดเดี่ยว|ไม่มีใครเข้าใจ|เหนื่อย(ล้า)?กับชีวิต|เหนื่อยเหลือเกิน|ไม่อยากอยู่|อยากหายไป|ทำร้ายตัวเอง|ไม่ไหวแล้ว|ท้อ(แท้|มาก)|ทุกข์ใจ|มืดมน|ร้องไห้(ทุกวัน|บ่อย)|จัดการอารมณ์.*ไม่ได้|วิบากกรรม.*(ชีวิต|มรสุม)|มรสุมชีวิต/.test(
    text,
  );
}

