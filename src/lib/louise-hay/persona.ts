export type LouiseHayChatMessage = { role: "user" | "assistant"; content: string };

export type LouiseHayPassage = {
  title: string;
  startPage: number | null;
  endPage: number | null;
  text: string;
};

function formatPassages(passages: readonly LouiseHayPassage[]): string {
  if (passages.length === 0) {
    return "(ไม่มีคำสอนอ้างอิงที่ตรงพอสำหรับคำถามนี้ — ตอบจากหัวใจความเชื่อหลักได้เลย)";
  }
  // ไม่ใส่เลขกำกับ/ชื่อหนังสือ/เลขหน้า เพื่อไม่ให้โมเดลลอกเลขอ้างอิง [1] (2) หรือเอ่ยชื่อหนังสือออกมา
  return passages.map((p) => p.text.trim()).join("\n\n———\n\n");
}

function formatConversation(messages: readonly LouiseHayChatMessage[]): string {
  return messages
    .map((m) => `${m.role === "assistant" ? LOUISE_HAY_ASSISTANT_NAME : "ผู้ใช้"}: ${m.content}`)
    .join("\n\n");
}

/** สร้าง systemInstruction + userPrompt สำหรับเรียก Gemini (grounded ด้วยคำสอน + ดวง ถ้ามี) */
/** วันนี้แบบไทยเต็ม (Asia/Bangkok, พ.ศ.) เช่น "วันพฤหัสบดีที่ 9 กรกฎาคม พ.ศ. 2569" */
function thaiFullDate(now: Date): string {
  return new Intl.DateTimeFormat("th-TH-u-ca-buddhist", {
    timeZone: "Asia/Bangkok",
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(now);
}

export function buildLouiseHayPrompt(input: {
  messages: readonly LouiseHayChatMessage[];
  passages: readonly LouiseHayPassage[];
  latestUserMessage: string;
  /** ผลจากศาสตร์ที่ระบบเลือกให้ (ดวง NewData / ปฏิทิน / ไพ่) — ใช้เป็นแกนคำตอบ เรียบเรียงด้วยน้ำเสียงฮีลใจ */
  groundingContext?: string | null;
  /** ผู้ใช้อยู่ในโทนซึมเศร้า/ทุกข์ใจ → แนบคำสั่งห่วงใย + แนะนำสายด่วน 1323 อย่างนุ่มนวล */
  emotionalDistress?: boolean;
  /** เวลาปัจจุบัน — ใช้บอกวันนี้ให้โมเดล กันการเดาวันที่ผิด (ค่าเริ่มต้น = ตอนนี้) */
  now?: Date;
}): { systemInstruction: string; userPrompt: string } {
  const recent = input.messages.slice(-8);
  return {
    systemInstruction: LOUISE_HAY_PERSONA,
    userPrompt: [
      `(ข้อเท็จจริงวันนี้ — ใช้อ้างอิงเสมอ ห้ามเดาวันที่เอง): วันนี้คือ ${thaiFullDate(input.now ?? new Date())}`,
      input.emotionalDistress ? EMOTIONAL_DISTRESS_INSTRUCTION : null,
      "คำสอนอ้างอิง (แก่นคิดจากหนังสือ Louise Hay — ใช้เป็นแรงบันดาลใจ เรียบเรียงใหม่ด้วยภาษาของคุณ):",
      formatPassages(input.passages),
      input.groundingContext
        ? `———\nผลจากศาสตร์ที่ระบบเลือกให้ (ใช้เป็นแกนคำตอบ แปลเป็นภาษาคนธรรมดา โยงเข้าเรื่องที่ถาม อบอุ่นแต่ฟันธงชัดตามที่ผลชี้ ไม่พูดกำกวม):\n${input.groundingContext}`
        : null,
      "———",
      "บทสนทนาก่อนหน้า:",
      formatConversation(recent),
      "———",
      `สิ่งที่ผู้ใช้เพิ่งพิมพ์: ${input.latestUserMessage}`,
      `ตอบในฐานะ "${LOUISE_HAY_ASSISTANT_NAME}": ตอบ "ตรงคำถาม" ที่เขาถามให้เป็นรูปธรรมและกระชับ (ปกติ 2-3 ย่อหน้าสั้น ๆ เข้าประเด็นเร็ว ไม่ยืดเยื้อ ไม่ไล่ท่องข้อมูลทุกจุด) **ฟันธงให้ชัดตามที่ผลชี้ ห้ามพูดกำกวมหรือใช้คำเผื่อ (อาจจะ/น่าจะ/ค่อนข้าง)** ห่อด้วยน้ำเสียงอบอุ่น แล้วปิดท้ายด้วยคำยืนยัน 1 บรรทัด (นำหน้าด้วย 💗)`,
    ]
      .filter((section): section is string => section !== null)
      .join("\n\n"),
  };
}
