/** เลือกคำยืนยันแบบสุ่ม (รับ seed จากภายนอกได้ เพื่อความ deterministic ในเทสต์) */
export function pickAffirmation(seed = Math.random()): string {
  const idx = Math.floor(seed * LOUISE_HAY_AFFIRMATIONS.length) % LOUISE_HAY_AFFIRMATIONS.length;
  return LOUISE_HAY_AFFIRMATIONS[idx];
}
