export function fengshuiAnswerBlock(fengshuiReading: string, fortuneOpener: string, count = 3): string {
  const text = [
          "คำถามนี้เป็นเรื่อง \"สถานที่/ฮวงจุ้ย (ชัยภูมิ)\" ที่พื้นดวงปาจื่อตอบไม่ได้ — ระบบจั่ว \"ไพ่อาถรรพ์ฮวงจุ้ย\" มาให้ 3 จุดแล้ว. **ห้ามขึ้นดวง/ห้ามอ้างผังชะตา/ห้ามมโนเสา-ธาตุ-ปีจร** ให้ตอบจากตำราฮวงจุ้ย 3 จุดนี้เท่านั้น:",
          fengshuiReading ?? "",
          [
            "วิธีตอบ:",
            `- **เปิดคำตอบด้วยคำทำนองว่า "${fortuneOpener}" สักครั้ง** แล้ว \"ประเมินภาพรวม\" ของสถานที่นี้ก่อนว่าฮวงจุ้ย \"ดีมาก / ดีน้อย / เสียน้อย / เสียมาก\" (ตีความเอาเองจาก 3 จุดที่จั่วได้ ว่าโน้มไปทางจุดเสียหรือจุดดีมากกว่า) — ซินแสนุ้ยสั่ง: ทุกที่ไม่มีฮวงจุ้ยดีที่สุด มีแต่เสียมาก-เสียน้อย`,
            "- ไล่ทีละจุด (3 จุด): จุดนั้นคือตำแหน่ง/สภาพอะไร ส่งผลอะไร (จากความหมาย+ข้อควรระวัง) แล้วฟันธง \"วิธีแก้\" ที่จับต้องได้ (จากคำแนะนำแก้ไขของจุดนั้น). ถ้าจุดไหนเป็นมงคล (เช่น หงส์แดง/เสือขาว/มังกรเขียว/สิงโตคู่) ให้บอกว่าเป็นด้านดี เสริมอะไร",
            "- **ห้ามบอกที่มา/วิธี — ห้ามระบุว่าเป็น \"ไพ่\" ห้ามบอกชื่อไพ่ ห้ามพูดว่า \"จั่วไพ่ได้...\"/\"เปิดไพ่\"** (ซินแสนุ้ยสั่ง: ในแชทบอกว่าเป็นไพ่แล้วคนจะเอ๊ะว่ารู้ได้ไง) — พูดเหมือนซินแสตรวจชัยภูมิให้ ใช้เนื้อจุดเหล่านี้เป็นคำตอบ",
            "- โทนซินแสตรวจฮวงจุ้ย อบอุ่นแต่ฟันธง เนื้อไม่ต้องลอกเป๊ะ เรียบเรียงเป็นภาษาพูดได้ **ห้ามเพิ่มจุดเสีย/คำแนะนำนอกเหนือจาก 3 จุดที่ให้มา**",
            "- **ห้ามชวนไปเมนูอื่น** ตอบให้เสร็จในนี้ ถ้าผู้ใช้อยากตรวจห้อง/จุดอื่นต่อ ให้บอกว่าถามมาได้เลย (จะตรวจให้ใหม่)",
          ].join("\n"),
  ].join("\n\n");
  return count === 3 ? text : text.split("3 จุด").join(count + " จุด");
}

/** เซียมซีเคี้ยงคุง 80 ใบ (ซินแสนุ้ย 2026-10-15): การชี้แนะ แผนงาน การตัดสินใจ ขอความเห็น · 1 คำถาม = 1 ใบ
 *  "ให้เสี่ยวมู่พูดออกไปเลย ไม่ต้องเอ่ยถึงไพ่" */
export function siamsiAnswerBlock(
  siamsiReading: string,
  fortuneOpener: string,
  /** คำลงท้ายตาม persona — ตัวอย่างประโยคตายตัว "ครับ" ทำให้เสี่ยวมี่ลอกไปตอบเป็นครับ (เอ็ม 2026-10-03) */
  ends: { polite: string; soft: string } = { polite: "ครับ", soft: "นะครับ" },
): string {
  return [
          "คำถามนี้เป็นเรื่อง \"ขอคำชี้แนะ / แผนงาน / การตัดสินใจ / ขอความเห็น\" ในเรื่องเฉพาะ หรือผู้ใช้ขอเสี่ยงเซียมซี — ระบบเสี่ยง \"ไพ่เซียมซีเคี้ยงคุง\" มาให้ 1 ใบแล้ว. **ห้ามขึ้นดวง/ห้ามอ้างผังชะตา/ห้ามมโนเสา-ธาตุ-ปีจร** ให้ตอบจากเนื้อใบนี้เท่านั้น:",
          siamsiReading ?? "",
          [
            "วิธีตอบ:",
            `- **ต้องเปิดคำตอบด้วยคำทำนองว่า "${fortuneOpener}" สักครั้ง** (เช่น "ลอง${fortuneOpener}ดูแล้ว${ends.soft}"/"${fortuneOpener}ให้แล้ว${ends.polite}") แล้วฟันธงตอบเรื่องที่ถามตรง ๆ ก่อน (ควรไปต่อ / รอจังหวะ / ปรับแผน / เลือกทางไหน) จาก "สถานการณ์" ของใบนี้`,
            "- ต่อด้วยสิ่งที่ต้องระวัง (จากข้อควรระวัง) และสิ่งที่ควรทำจริง ๆ (จากคำแนะนำ) ให้จับต้องได้ เข้ากับเรื่องของผู้ถาม",
            "- **ห้ามบอกที่มา/วิธี — ห้ามระบุว่าเป็น \"ไพ่\" ห้ามบอกชื่อไพ่/เลขไพ่ ห้ามมีคำว่า \"ไพ่\"/\"เซียมซี\" ในคำตอบ ห้ามพูดว่า \"จั่ว/เสี่ยงได้...\"** (ซินแสนุ้ย: ให้เสี่ยวมู่พูดออกไปเลย ไม่ต้องเอ่ยถึงไพ่) — พูดเหมือนซินแสให้คำแนะนำเอง",
            "- โทน \"รู้ใจ\" เหมือนผู้ใหญ่/เพื่อนที่ทักตรงใจ อบอุ่นแต่ชัดเจน ไม่ใช่บอกลอย ๆ ว่า \"อย่าคิดมาก\" — เรียบเรียงเป็นภาษาพูดได้ แต่ **ห้ามเพิ่มคำทำนาย/คำแนะนำนอกเหนือจากเนื้อใบนี้**",
            "- เรื่องสุขภาพ/การเงิน/กฎหมาย ให้แนะนำแบบระมัดระวัง ไม่ฟันธงเกินจริง",
            "- สั้น กระชับ ไม่กี่ประโยค **ห้ามชวนไปเมนูอื่น** ตอบให้เสร็จในนี้",
          ].join("\n"),
  ].join("\n\n");
}

